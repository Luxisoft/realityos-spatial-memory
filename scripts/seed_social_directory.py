def stable_uuid(kind: str, slug: str) -> uuid.UUID:
    return uuid.uuid5(NAMESPACE, f"{kind}:{slug}")


def ensure_generated_assets(
    slug: str, require_photos: bool = True
) -> tuple[Path, list[Path], list[Path]]:
    source = SOURCE_ROOT / f"{slug}.png"
    if not source.exists():
        raise FileNotFoundError(f"Missing generated source portrait: {source}")
    target = GENERATED_ROOT / slug
    target.mkdir(parents=True, exist_ok=True)
    avatar = target / "avatar.jpg"
    with Image.open(source) as original:
        base = ImageOps.exif_transpose(original).convert("RGB")
        avatar_image = ImageOps.fit(base, (640, 640), method=Image.Resampling.LANCZOS)
        avatar_image.save(avatar, quality=90, optimize=True)
    muse_dir = MUSE_ROOT / slug
    photos = [muse_dir / f"photo-{index + 1:02d}.jpg" for index in range(PHOTOS_PER_PROFILE)]
    if require_photos:
        missing = [path for path in photos if not path.is_file()]
        if missing:
            names = ", ".join(path.name for path in missing)
            raise FileNotFoundError(
                f"Missing Muse photos for {slug}: {names}. "
                "Run scripts/generate_directory_photos.py first."
            )
    return avatar, photos, []


def local_fetch(url: str) -> bytes:
    prefix = "fixture://"
    if not url.startswith(prefix):
        raise ValueError("Fixture importer only accepts fixture URLs.")
    path = (FIXTURE_ROOT / url.removeprefix(prefix)).resolve()
    if FIXTURE_ROOT.resolve() not in path.parents or not path.is_file():
        raise ValueError("Fixture path is unavailable.")
    return path.read_bytes()


def scene_caption(slug: str, filename: str, profession: str, region: str, index: int) -> str:
    manifest = MUSE_ROOT / slug / "manifest.json"
    if manifest.is_file():
        try:
            import json

            scenes = json.loads(manifest.read_text()).get("scenes", {})
            scene = scenes.get(filename.removesuffix(".jpg"), {}).get("scene")
            if scene:
                return f"{profession} · {region} · {scene}"
        except (ValueError, OSError):
            pass
    return f"{profession} · {region} · escena {index + 1}"


def upsert_member(db, workspace: Workspace, user: User, role: Role = Role.QUERY) -> None:
    existing = db.scalar(
        select(WorkspaceMember).where(
            WorkspaceMember.workspace_id == workspace.id,
            WorkspaceMember.user_id == user.id,
        )
    )
    if existing is None:
        db.add(WorkspaceMember(workspace_id=workspace.id, user_id=user.id, role=role))


def seed_profile(db, settings, workspace: Workspace, row, index: int) -> None:
    slug, name, profession, region, gender, tags = row
    avatar, photos, _videos = ensure_generated_assets(slug)
    user_id = stable_uuid("user", slug)
    user = db.get(User, user_id)
    if user is None:
        user = User(
            id=user_id,
            email=f"{slug}@directory.realityos.invalid",
            display_name=name,
            password_hash=hash_password(uuid.uuid4().hex),
        )
        db.add(user)
        db.flush()
    custom = db.get(UserProfile, user.id)
    if custom is None:
        custom = UserProfile(user_id=user.id)
        db.add(custom)
    custom.headline = profession
    custom.biography = f"{profession} en {region}. Experiencia en {tags.replace(' ', ', ')}."
    custom.website = f"https://example.invalid/{slug}"
    custom.social_links = [{"label": "Portafolio", "url": f"https://example.invalid/{slug}/work"}]
    facebook = db.get(FacebookProfile, user.id)
    if facebook is None:
        facebook = FacebookProfile(user_id=user.id)
        db.add(facebook)
    facebook.gender = gender
    facebook.hometown = region
    facebook.location = region
    facebook.picture_url = f"fixture://generated/{slug}/{avatar.name}"
    facebook.photos_count = PHOTOS_PER_PROFILE
    facebook.videos_count = 0
    facebook.friends_count = 8 + (index * 13) % 220
    facebook.likes_count = 5 + (index * 17) % 180
    facebook.granted_scopes = ["public_profile", "user_photos", "user_videos"]
    facebook.sync_diagnostics = {"photos": "ready", "videos": "ready"}
    facebook.synced_at = datetime.now(UTC)
    upsert_member(db, workspace, user)
    if db.get(BiometricConsent, user.id) is None:
        db.add(
            BiometricConsent(
                user_id=user.id,
                notice_version=settings.biometric_notice_version,
            )
        )
    started = datetime(2026, 10, 1, 12, tzinfo=UTC) - timedelta(days=index * 2)
    for media_index, path in enumerate(photos):
        fb_id = f"directory-{slug}-photo-{media_index + 1:02d}"
        item = db.get(FacebookMedia, fb_id)
        if item is None:
            db.add(
                FacebookMedia(
                    fb_id=fb_id,
                    user_id=user.id,
                    kind="photo",
                    source_url=f"fixture://muse/{slug}/{path.name}",
                    caption=scene_caption(slug, path.name, profession, region, media_index),
                    fb_created_time=(started - timedelta(days=media_index)).isoformat(),
                )
            )
    db.flush()
    import_facebook_media(db, settings, user.id, fetch_bytes=local_fetch)
    avatar_asset = next(
        (
            asset
            for asset in db.scalars(
                select(MediaAsset)
                .join(CaptureSession, CaptureSession.id == MediaAsset.capture_session_id)
                .where(CaptureSession.created_by_id == user.id)
                .order_by(MediaAsset.created_at.desc())
            )
            if (asset.extra_metadata or {}).get("face_profile_picture")
        ),
        None,
    )
    if avatar_asset is not None:
        custom.avatar_media_id = avatar_asset.id
    publications = list(
        db.scalars(
            select(Publication)
            .where(
                Publication.owner_id == user.id,
                Publication.source.in_(["facebook", "simulator"]),
            )
            .order_by(Publication.published_at.desc())
        )
    )
    for publication in publications:
        publication.audience = "public"
        publication.source = "simulator"
        publication.search_text = f"{publication.caption} {profession} {region} {tags}"
    photo_publication = next((item for item in publications if db.get(MediaAsset, item.media_id).mime_type.startswith("image/")), None)
    work_publications = list(
        db.scalars(
            select(Publication).where(
                Publication.owner_id == user.id,
                Publication.source == "simulator-work",
                Publication.audience == "work",
            )
        )
    )
    # Directory profiles no longer ship synthetic videos: drop stale video refs.
    for stale in [
        item
        for item in work_publications
        if db.get(MediaAsset, item.media_id) is None
        or db.get(MediaAsset, item.media_id).mime_type.startswith("video/")
    ]:
        work_publications.remove(stale)
        db.delete(stale)
    if photo_publication is not None:
        ref = f"work-{slug}-photo"
        matching = [
            item
            for item in work_publications
            if db.get(MediaAsset, item.media_id) is not None
            and db.get(MediaAsset, item.media_id).mime_type.startswith("image/")
        ]
        existing = next(
            (item for item in matching if item.source_ref == ref),
            matching[0] if matching else None,
        )
        for duplicate in matching:
            if duplicate is existing:
                continue
            db.delete(duplicate)
        if existing is None:
            db.add(
                Publication(
                    owner_id=user.id,
                    media_id=photo_publication.media_id,
                    audience="work",
                    workspace_id=workspace.id,
                    caption=photo_publication.caption,
                    search_text=photo_publication.search_text,
                    source="simulator-work",
                    source_ref=ref,
                    published_at=photo_publication.published_at,
                )
            )
        else:
            existing.media_id = photo_publication.media_id
            existing.workspace_id = workspace.id
            existing.caption = photo_publication.caption
            existing.search_text = photo_publication.search_text
            existing.source_ref = ref
            existing.published_at = photo_publication.published_at


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--prepare-only", action="store_true")
    args = parser.parse_args()
    SOURCE_ROOT.mkdir(parents=True, exist_ok=True)
    GENERATED_ROOT.mkdir(parents=True, exist_ok=True)
    MUSE_ROOT.mkdir(parents=True, exist_ok=True)
    for slug, *_ in PROFILE_ROWS:
        ensure_generated_assets(slug, require_photos=not args.prepare_only)
    if args.prepare_only:
        return
    settings = get_settings()
    database = Database(settings.database_url)
    with database.session_factory() as db:
        first_id = stable_uuid("user", PROFILE_ROWS[0][0])
        owner = db.get(User, first_id)
        if owner is None:
            owner = User(
                id=first_id,
                email=f"{PROFILE_ROWS[0][0]}@directory.realityos.invalid",
                display_name=PROFILE_ROWS[0][1],
                password_hash=hash_password(uuid.uuid4().hex),
            )
            db.add(owner)
            db.flush()
        workspace = db.scalar(select(Workspace).where(Workspace.name == DEMO_WORKSPACE))
        if workspace is None:
            workspace = Workspace(
                id=stable_uuid("workspace", "demo-team"),
                name=DEMO_WORKSPACE,
                description="Directorio audiovisual para pruebas de búsqueda",
                created_by_id=owner.id,
            )
            db.add(workspace)
            db.flush()
        for active_user in db.scalars(select(User).where(User.is_active.is_(True))):
            upsert_member(db, workspace, active_user, Role.ADMIN if active_user.id == owner.id else Role.QUERY)
        db.commit()
    for index, row in enumerate(PROFILE_ROWS):
        with database.session_factory() as db:
            workspace = db.get(Workspace, stable_uuid("workspace", "demo-team"))
            seed_profile(db, settings, workspace, row, index)
            db.commit()
            print(f"seeded {index + 1:02d}/{len(PROFILE_ROWS):02d} {row[0]}")


if __name__ == "__main__":
    main()
