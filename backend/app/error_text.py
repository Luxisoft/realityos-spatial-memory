# Only application-owned templates are substituted. Captured values, external
# errors and unrecognized messages are returned byte-for-byte unchanged.
TEMPLATES = (
    (r"Video exceeds the (\d+)-second limit\.", "El video supera el límite de {0} segundos."),
    (r"Video exceeds (\d+) seconds\.", "El video supera {0} segundos."),
    (r"Unresolved relationships for (.+)\.", "Hay relaciones sin resolver para {0}."),
    (
        r"Version must increase and kind must stay unchanged: (.+)\.",
        "La versión debe aumentar y el tipo debe mantenerse: {0}.",
    ),
)


def error_text(message: str, language: str) -> str:
    if language != "es":
        return message
    if message in SPANISH:
        return SPANISH[message]
    for pattern, translated in TEMPLATES:
        if match := re.fullmatch(pattern, message):
            return translated.format(*match.groups())
    return message
